'use strict';
const fs = require('node:fs/promises');
const path = require('node:path');
const vm = require('node:vm');
const { createHash } = require('node:crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');

async function main(){
  const window = {};
  vm.runInNewContext(await fs.readFile(path.join(root, 'js/projects.js'), 'utf8'), { window });
  const projects = window.VASTUCHITRA.projects.filter(project => !project.id.startsWith('meeting-'));
  const dir = path.join(root, 'public', 'previews');
  let config = {};
  try { config = JSON.parse(await fs.readFile(path.join(root, 'media-config.json'), 'utf8')); }
  catch (error){ if (error.code !== 'ENOENT') throw error; }
  const library = path.resolve(root, config.rootPath || 'assets');
  await fs.mkdir(dir, { recursive:true });
  const previews = {};
  async function preview(url, file, width){
    const key = createHash('sha256').update(url).digest('hex').slice(0,16) + '.webp';
    await sharp(file, { unlimited:true, sequentialRead:true }).rotate()
      .resize({ width, height:width, fit:'inside', withoutEnlargement:true })
      .webp({ quality:76 }).toFile(path.join(dir,key));
    return previews[url] = '/public/previews/' + key;
  }
  const portable = [];
  for (const project of projects){
    const slides = [];
    for (const slide of project.slides || []){
      const item = typeof slide === 'string' ? { src:slide } : slide;
      const url = new URL(item.src, 'http://localhost');
      const name = url.pathname === '/api/media-preview' ? url.searchParams.get('path') :
        url.pathname.startsWith('/media/') ? decodeURIComponent(url.pathname.slice(7)) : null;
      const file = name && path.resolve(library, name);
      if (!file || !file.startsWith(library + path.sep)) continue;
      const src = previews[item.src] || await preview(item.src,file,1200);
      slides.push({ src, pos:item.pos });
    }
    if (!slides.length) continue;
    const { id,title,cat,sub,icon,accent,size,desc,specs,fx,interval,dir:direction } = project;
    portable.push({ id,title,cat,sub,icon,accent,size,desc,specs,fx,interval,dir:direction,slides,action:{type:'detail'} });
  }
  for (const [folder,width] of [['demo',1200],['temple',600]]){
    for (const name of await fs.readdir(path.join(root,'public',folder))){
      if (!/\.(webp|jpe?g)$/i.test(name)) continue;
      const url = '/public/' + folder + '/' + encodeURIComponent(name);
      await preview(url,path.join(root,'public',folder,name),width);
    }
  }
  await fs.writeFile(path.join(root,'js','portable-media.js'),
    '// Generated by scripts/build-previews.cjs.\nwindow.VASTUCHITRA_PREVIEWS = ' + JSON.stringify(previews,null,2) +
    ';\nwindow.VASTUCHITRA_PORTABLE_PROJECTS = ' + JSON.stringify(portable,null,2) + ';\n');
  console.log(`Built ${Object.keys(previews).length} previews and ${portable.length} portable project galleries.`);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
